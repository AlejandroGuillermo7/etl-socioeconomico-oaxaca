-- Data warehouse: modelo estrella del proyecto (mismo diseño de la unidad anterior).
-- IF NOT EXISTS permite ejecutarlo aunque las tablas ya existan en la instancia EC2.

CREATE TABLE IF NOT EXISTS dim_geografia (
    sk_geografia INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    clave_geo VARCHAR(5) NOT NULL UNIQUE,
    nivel VARCHAR(20) NOT NULL,
    clave_entidad CHAR(2) NOT NULL,
    clave_municipio CHAR(3),
    nombre VARCHAR(120) NOT NULL
);

CREATE TABLE IF NOT EXISTS dim_tiempo (
    sk_tiempo INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    anio INTEGER NOT NULL,
    periodo VARCHAR(60) NOT NULL,
    fecha_referencia DATE,
    tipo_referencia VARCHAR(100) NOT NULL,
    UNIQUE (anio, periodo, tipo_referencia)
);

CREATE TABLE IF NOT EXISTS dim_indicador (
    sk_indicador INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_origen VARCHAR(60) NOT NULL,
    nombre VARCHAR(150) NOT NULL,
    categoria VARCHAR(70),
    unidad VARCHAR(60),
    fuente_api VARCHAR(100) NOT NULL,
    UNIQUE (codigo_origen, fuente_api)
);

CREATE TABLE IF NOT EXISTS dim_actividad (
    sk_actividad INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    codigo_scian VARCHAR(10) NOT NULL UNIQUE,
    nivel_scian VARCHAR(60),
    descripcion VARCHAR(200),
    codigo_padre VARCHAR(10)
);

CREATE TABLE IF NOT EXISTS fact_indicadores (
    id_hecho BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    sk_geografia INTEGER NOT NULL REFERENCES dim_geografia(sk_geografia),
    sk_indicador INTEGER NOT NULL REFERENCES dim_indicador(sk_indicador),
    sk_tiempo INTEGER NOT NULL REFERENCES dim_tiempo(sk_tiempo),
    sk_actividad INTEGER NOT NULL REFERENCES dim_actividad(sk_actividad),
    valor NUMERIC(24,8),
    fecha_carga TIMESTAMP DEFAULT CURRENT_TIMESTAMP,
    UNIQUE (sk_geografia, sk_indicador, sk_tiempo, sk_actividad)
);
